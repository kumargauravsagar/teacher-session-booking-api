
import { PipelineStage, Types } from 'mongoose';
import { ISession, Session } from '../models/session.model';
import { Teacher } from '../models/teacher.model';
import { User } from '../models/user.model';
import { ApiError } from '../utils/ApiError';
import { CreateSessionInput } from '../validators/session.validator';

const DAY_MS = 24 * 60 * 60 * 1000;

/** Teacher fields that are safe to expose publicly. */
const TEACHER_LOOKUP: PipelineStage.Lookup = {
  $lookup: {
    from: 'teachers',
    localField: 'teacherId',
    foreignField: '_id',
    as: 'teacher',
  },
};

const SESSION_PROJECTION: PipelineStage.Project = {
  $project: {
    _id: 0,
    id: '$_id',
    startTime: 1,
    endTime: 1,
    status: 1,
    userId: 1,
    completedAt: 1,
    teacherId: 1,
    createdAt: 1,
    updatedAt: 1,
    teacher: {
      id: '$teacher._id',
      fullName: '$teacher.fullName',
      specialization: '$teacher.specialization',
      experience: '$teacher.experience',
    },
  },
};

export async function createSession(
  input: CreateSessionInput,
): Promise<ISession> {
  const teacherExists = await Teacher.exists({ _id: input.teacherId });

  if (!teacherExists) {
    throw ApiError.notFound('Teacher not found');
  }

  // The server controls status, userId and completedAt.
  return Session.create({
    teacherId: input.teacherId,
    startTime: input.startTime,
    endTime: input.endTime,
  });
}

/** UTC [start, end) boundaries for the day containing a Unix-ms timestamp. */
export function utcDayRange(
  timestampMs: number,
): { start: Date; end: Date } {
  const startMs = Math.floor(timestampMs / DAY_MS) * DAY_MS;

  return {
    start: new Date(startMs),
    end: new Date(startMs + DAY_MS),
  };
}

export async function getAvailableSessions(
  timestampMs: number,
): Promise<unknown[]> {
  const { start, end } = utcDayRange(timestampMs);

  const pipeline: PipelineStage[] = [
    // Only available sessions starting within the requested UTC day.
    {
      $match: {
        status: 'AVAILABLE',
        startTime: { $gte: start, $lt: end },
      },
    },
    TEACHER_LOOKUP,
    { $unwind: '$teacher' },
    SESSION_PROJECTION,
    { $sort: { startTime: 1, id: 1 } },
  ];

  return Session.aggregate(pipeline);
}

export async function bookSession(
  sessionId: string,
  userId: string,
): Promise<ISession> {
  const userExists = await User.exists({ _id: userId });

  if (!userExists) {
    throw ApiError.notFound('User not found');
  }

  // Atomic compare-and-set prevents concurrent double booking.
  const booked = await Session.findOneAndUpdate(
    { _id: sessionId, status: 'AVAILABLE' },
    {
      $set: {
        status: 'BOOKED',
        userId: new Types.ObjectId(userId),
      },
    },
    { returnDocument: 'after' },
  );

  if (booked) {
    return booked;
  }

  const existing = await Session.exists({ _id: sessionId });

  if (!existing) {
    throw ApiError.notFound('Session not found');
  }

  throw ApiError.conflict('Session is not available for booking');
}

export async function completeSession(
  sessionId: string,
): Promise<ISession> {
  // Only BOOKED sessions can be completed.
  // completedAt is generated by the server.
  const completed = await Session.findOneAndUpdate(
    { _id: sessionId, status: 'BOOKED' },
    {
      $set: {
        status: 'COMPLETED',
        completedAt: new Date(),
      },
    },
    { returnDocument: 'after' },
  );

  if (completed) {
    return completed;
  }

  const existing = await Session.exists({ _id: sessionId });

  if (!existing) {
    throw ApiError.notFound('Session not found');
  }

  throw ApiError.conflict(
    'Only BOOKED sessions can be marked as completed',
  );
}

export async function getUserSessions(
  userId: string,
): Promise<{
  upcomingSessions: unknown[];
  completedSessions: unknown[];
}> {
  const userExists = await User.exists({ _id: userId });

  if (!userExists) {
    throw ApiError.notFound('User not found');
  }

  const now = new Date();

  const pipeline: PipelineStage[] = [
    { $match: { userId: new Types.ObjectId(userId) } },
    TEACHER_LOOKUP,
    { $unwind: '$teacher' },
    SESSION_PROJECTION,
    {
      $facet: {
        upcomingSessions: [
          {
            $match: {
              status: 'BOOKED',
              startTime: { $gte: now },
            },
          },
          { $sort: { startTime: 1, id: 1 } },
        ],
        completedSessions: [
          { $match: { status: 'COMPLETED' } },
          { $sort: { startTime: 1, id: 1 } },
        ],
      },
    },
  ];

  const [result] = await Session.aggregate<{
    upcomingSessions: unknown[];
    completedSessions: unknown[];
  }>(pipeline);

  return {
    upcomingSessions: result?.upcomingSessions ?? [],
    completedSessions: result?.completedSessions ?? [],
  };
}
